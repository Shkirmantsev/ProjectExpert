"""Synthetic PDF fixture generator tests.

The v0.8 Tier-2 eval corpus needs sanitised 10 / 100 / 600
PDF fixtures under ``evals/corpus/generated-pdf/`` (Change
Package J, plan §28). The fixtures are generated by
``scripts/generate_pdf_fixtures.py`` using a stdlib-only
PDF builder. These tests pin the generator's contract:

* the byte stream starts with the PDF magic header;
* the xref table covers every object (Catalog + Pages + N
  Page/Content pairs + 1 Font);
* the page count matches the requested value;
* the manifest.json is byte-stable and references every
  golden query chunk anchor.
"""

from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path


__all__ = ["PdfFixtureGeneratorTests"]


class PdfFixtureGeneratorTests(unittest.TestCase):

    def test_build_pdf_has_valid_minimal_structure(self) -> None:
        from scripts.generate_pdf_fixtures import build_pdf
        for size in (1, 10, 100):
            data = build_pdf(page_count=size, title="Test PDF")
            self.assertTrue(data.startswith(b"%PDF-1.4"),
                            f"PDF {size} lacks header")
            self.assertIn(b"%%EOF", data)
            self.assertIn(b"xref", data)
            self.assertIn(b"trailer", data)
            # 1 Catalog + 1 Pages + N Page + N Content + 1 Font
            # = 2N + 3 objects.
            expected_objects = 2 * size + 3
            # The xref header reads ``0 (N+1)`` so we can
            # count the trailing ``n `` entries.
            xref_start = data.index(b"xref\n")
            xref_section = data[xref_start:].split(b"trailer", 1)[0]
            n_entries = sum(
                1 for line in xref_section.splitlines()[1:]
                if line.endswith(b" n ")
            )
            self.assertEqual(
                n_entries, expected_objects,
                f"PDF {size}: expected {expected_objects} "
                f"objects, xref lists {n_entries}",
            )

    def test_build_pdf_rejects_non_positive_page_count(self) -> None:
        from scripts.generate_pdf_fixtures import build_pdf
        with self.assertRaises(ValueError):
            build_pdf(page_count=0, title="x")
        with self.assertRaises(ValueError):
            build_pdf(page_count=-1, title="x")

    def test_write_fixtures_emits_manifest(self) -> None:
        from scripts.generate_pdf_fixtures import write_fixtures
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "generated-pdf"
            manifest = write_fixtures(
                out, sizes=(10, 100, 600), title="Eval fixture",
            )
            self.assertEqual(manifest["corpus"], "generated-pdf")
            self.assertEqual(
                len(manifest["fixtures"]), 3,
            )
            for entry in manifest["fixtures"]:
                path = out / entry["filename"]
                self.assertTrue(path.exists())
                self.assertGreater(path.stat().st_size, 100)
            manifest_path = out / "manifest.json"
            self.assertTrue(manifest_path.exists())
            loaded = json.loads(
                manifest_path.read_text(encoding="utf-8"),
            )
            self.assertEqual(loaded["corpus"], "generated-pdf")
            for key in (
                "pdf-chunk-10-constraints-table",
                "pdf-chunk-100-arch-figure",
                "pdf-chunk-600-toc",
            ):
                self.assertIn(key, loaded["chunk_anchors"])

    def test_committed_corpus_fixtures_exist(self) -> None:
        # The committed eval corpus ships the canonical
        # 10/100/600 fixtures; the test pins the file
        # inventory so a follow-up commit cannot silently
        # drop a fixture.
        from pathlib import Path
        out = Path("evals/corpus/generated-pdf")
        for filename in ("10-page.pdf", "100-page.pdf",
                         "600-page.pdf", "manifest.json"):
            self.assertTrue(
                (out / filename).exists(),
                f"missing committed fixture: {filename}",
            )
        for filename, expected_pages in (
            ("10-page.pdf", 10),
            ("100-page.pdf", 100),
            ("600-page.pdf", 600),
        ):
            data = (out / filename).read_bytes()
            self.assertTrue(data.startswith(b"%PDF-1.4"))
            self.assertIn(f"Page 1 / {expected_pages}".encode(),
                          data)
            self.assertIn(f"Page {expected_pages} / {expected_pages}"
                          .encode(), data)


if __name__ == "__main__":  # pragma: no cover
    unittest.main()